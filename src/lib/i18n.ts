const dictionaries: Record<Locale, Dict> = { zh, en };

export type TranslationKey = keyof typeof zh;

export function translate(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>): string {
  const dict = dictionaries[locale] ?? dictionaries.zh;
  let text = dict[key] ?? dictionaries.zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value));
    }
  }
  return text;
}
